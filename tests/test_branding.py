"""No watermarks or AI/Muse branding anywhere in shipped files."""

import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
BANNED = [
    re.compile(r"\bMuse\b", re.IGNORECASE),
    re.compile(r"AI[- ]generated", re.IGNORECASE),
    re.compile(r"generated by an AI", re.IGNORECASE),
    re.compile(r"watermark", re.IGNORECASE),
    re.compile(r"Anthropic", re.IGNORECASE),
    re.compile(r"Claude", re.IGNORECASE),
]
# The research notes legitimately name trending repos (e.g. claude-mem) and
# paper authors; the branding rule covers attribution headers/footers in
# shipped code and docs, not research citations. Only scan code/docs/README/
# scripts, excluding the research log.
SKIP_DIRS = {".venv", "venv", "__pycache__", ".pytest_cache", ".git",
             "results", "blocklock-venv"}
SKIP_FILES = {"test_branding.py", "RESEARCH.md"}


def _files():
    for path in sorted(ROOT.rglob("*")):
        if not path.is_file():
            continue
        if any(part in SKIP_DIRS for part in path.parts):
            continue
        if path.name in SKIP_FILES:
            continue
        if path.suffix in {".py", ".md", ".toml", ".txt", ".yml", ".cfg"}:
            yield path


def test_no_branding():
    hits = []
    for path in _files():
        text = path.read_text(errors="ignore")
        for pat in BANNED:
            if pat.search(text):
                hits.append(f"{path.relative_to(ROOT)}: {pat.pattern}")
    assert not hits, "\n".join(hits)
